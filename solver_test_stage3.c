enum {
    CUBIES = 7,
    PERMUTATIONS = 5040,
    STATES_P = PERMUTATIONS,
    ORIENTATIONS = 729,
    STATES_O = ORIENTATIONS,
    MOVES = 9
};

typedef struct {
    uint8_t p[CUBIES], o[CUBIES];
} state_t;

static const char *const move_names[MOVES] = {"R",  "R2", "R'", "B", "B2",
                                              "B'", "D",  "D2", "D'"};
static const uint8_t inverse_move[MOVES] = {2, 1, 0, 5, 4, 3, 8, 7, 6};
static const uint8_t source[3][CUBIES] = {
    {1, 4, 2, 0, 3, 5, 6},
    {0, 1, 2, 4, 5, 6, 3},
    {0, 2, 5, 3, 1, 4, 6},
};
static const uint8_t twist[3][CUBIES] = {
    {1, 2, 0, 2, 1, 0, 0},
    {0, 0, 0, 1, 2, 1, 2},
    {0, 0, 0, 0, 0, 0, 0},
};
static const uint8_t mod3_table[5] = {0, 1, 2, 0, 1};
static const uint8_t face_table[MOVES]  = {0,0,0,1,1,1,2,2,2};
static const uint8_t turns_table[MOVES] = {1,2,3,1,2,3,1,2,3};

static state_t quarter_turn_p(state_t state, uint8_t face)
{
    state_t result;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t from = source[face][i];
        result.p[i] = state.p[from];
    }
    return result;
}
static state_t quarter_turn_o(state_t state, uint8_t face)
{
    state_t result;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t from = source[face][i];
        result.o[i] = (uint8_t) mod3_table[state.o[from] + twist[face][i]];
    }
    return result;
}

static state_t apply_move(state_t state, uint8_t move)
{
    uint8_t face = face_table[move];
    uint8_t turns = turns_table[move];
    for (uint8_t t = 0; t < turns; ++t) {
        state_t p_part = quarter_turn_p(state, face);
        state_t o_part = quarter_turn_o(state, face);
        state_t next;
        for (uint8_t i = 0; i < CUBIES; ++i) {
            next.p[i] = p_part.p[i];
            next.o[i] = o_part.o[i];
        }
        state = next;
    }
    return state;
}

static uint32_t permutation_rank(const state_t *state)
{
    uint32_t p = 0;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t smaller = 0;
        for (uint8_t j = (uint8_t) (i + 1U); j < CUBIES; ++j)
            smaller += (uint8_t)(state->p[j] < state->p[i]);
        p = p * (CUBIES - i) + smaller;
    }
    return p;
}
static uint32_t orientation_rank(const state_t *state)
{
    uint32_t o = 0;
    for (uint8_t i = 0; i < 6; ++i)
       o = (o << 1) + o + state->o[i];
    return o;
}

static void unrank_permutation(uint32_t rank, state_t *state)
{
    uint8_t available[CUBIES] = {0, 1, 2, 3, 4, 5, 6};
    uint32_t p = rank, f = 720;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        uint8_t q = (uint8_t) (p / f);
        p %= f;
        state->p[i] = available[q];
        for (uint8_t j = q; j + 1U < (uint8_t)(CUBIES - i); ++j)
            available[j] = available[j + 1U];
        if (i < 5)
            f /= 6U - i;
        state->o[i] = 0;
    }
}
static void unrank_orientation(uint32_t rank, state_t *state)
{
    uint32_t o = rank;
    uint8_t sum = 0;
    for (uint8_t i = 6; i-- > 0;) {
        state->o[i] = (uint8_t) (o % 3U);
        sum = (uint8_t) (sum + state->o[i]);
        o /= 3U;
        state->p[i] = (uint8_t) i;
    }
    state->o[6] = (uint8_t) ((3U - sum % 3U) % 3U);
    state->p[6] = 6;
}

static int valid(const state_t *state)
{
    uint8_t sum = 0;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        if (state->p[i] >= CUBIES || state->o[i] >= 3)
            return 0;
        for (uint8_t j = 0; j < i; ++j)
            if (state->p[j] == state->p[i])
                return 0;
        sum = (uint8_t) (sum + state->o[i]);
    }
    return sum % 3U == 0;
}

